#!/usr/bin/env python3
"""
Builds the phone app (webble/app.html) from its template (webble/app-vorlage.html) and the
shared look and result display of the bridge's web page (esp32-bridge/m18_bridge/web_ui.h,
between the SHARED-CSS-* and SHARED-JS-* markers) - so the app shows a read-out exactly like
the bridge does, with all 185 values.

    python esp32-bridge/tools/gen_app.py          # write webble/app.html
    python esp32-bridge/tools/gen_app.py --check  # exit 1 if webble/app.html is outdated (CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
WEB_UI = ROOT / "esp32-bridge" / "m18_bridge" / "web_ui.h"
TEMPLATE = ROOT / "webble" / "app-vorlage.html"
OUT = ROOT / "webble" / "app.html"


def block(src, name):
    m = re.search(r"/\*SHARED-%s-BEGIN[^*]*\*/\n(.*?)/\*SHARED-%s-END\*/" % (name, name), src, re.S)
    if not m:
        raise SystemExit(f"web_ui.h: markers SHARED-{name}-BEGIN/END not found")
    return m.group(1).rstrip("\n")


def build():
    src = WEB_UI.read_text(encoding="utf-8")
    tpl = TEMPLATE.read_text(encoding="utf-8")
    head = ("<!-- GENERATED by esp32-bridge/tools/gen_app.py from webble/app-vorlage.html and "
            "esp32-bridge/m18_bridge/web_ui.h - do not edit -->\n")
    out = tpl.replace("/*SHARED-CSS*/", block(src, "CSS")).replace("/*SHARED-JS*/", block(src, "JS"))
    out = re.sub(r"<!-- Vorlage der Handy-App.*?-->\n", "", out, flags=re.S)
    return out.replace("<!doctype html>\n", "<!doctype html>\n" + head, 1)


def main():
    new = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != new:
            print("webble/app.html outdated - run python esp32-bridge/tools/gen_app.py")
            return 1
        print("webble/app.html up to date")
        return 0
    OUT.write_text(new, encoding="utf-8")
    print(f"webble/app.html written ({len(new) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
