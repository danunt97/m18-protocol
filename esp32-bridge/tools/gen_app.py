#!/usr/bin/env python3
"""
Builds the Bluetooth app (webble/app.html, GitHub Pages /app/) from the bridge's own web page
(esp32-bridge/m18_bridge/web_ui.h) plus the Bluetooth adapter webble/ble-shim.js.

So there is ONE app: on the bridge it talks HTTP, on GitHub Pages the adapter answers the page's
/api/... calls over Bluetooth LE. Everything (read-out, all values, history, Wi-Fi setup, cloud
account, "Meine Akkus", linking the bridge) behaves the same on both ways.

    python esp32-bridge/tools/gen_app.py          # write webble/app.html
    python esp32-bridge/tools/gen_app.py --check  # exit 1 if webble/app.html is outdated (CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
WEB_UI = ROOT / "esp32-bridge" / "m18_bridge" / "web_ui.h"
SHIM = ROOT / "webble" / "ble-shim.js"
OUT = ROOT / "webble" / "app.html"

HEAD = ('<meta name="theme-color" content="#1b1d20">\n'
        '<link rel="manifest" href="manifest.webmanifest">\n'
        '<link rel="icon" href="icon.svg" type="image/svg+xml">\n'
        '<link rel="apple-touch-icon" href="icon.svg">\n')


def build():
    src = WEB_UI.read_text(encoding="utf-8")
    page = re.search(r'R"HTML\((.*)\)HTML"', src, re.S).group(1)
    shim = SHIM.read_text(encoding="utf-8")
    if page.count("<script>") != 1 or "<title>M18 Akku-Brücke</title>" not in page:
        raise SystemExit("web_ui.h: unexpected page layout (one <script>, title)")
    page = page.replace("<title>M18 Akku-Brücke</title>", "<title>M18 Akku-App</title>\n" + HEAD, 1)
    page = page.replace("<script>", "<script>\n" + shim + "</script>\n<script>", 1)
    note = ("<!-- GENERATED by esp32-bridge/tools/gen_app.py from esp32-bridge/m18_bridge/web_ui.h and "
            "webble/ble-shim.js - do not edit -->\n")
    return page.replace("<!doctype html>", "<!doctype html>\n" + note, 1)


def main():
    new = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != new:
            print("webble/app.html outdated - run python esp32-bridge/tools/gen_app.py")
            return 1
        print("webble/app.html up to date")
        return 0
    OUT.write_text(new, encoding="utf-8")
    print(f"webble/app.html written ({len(new) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
