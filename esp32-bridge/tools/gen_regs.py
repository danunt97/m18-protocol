# obvious typos in m18.py's labels (address -> corrected range)
TYPO = {0x907C: "70-75A", 0x90E8: "Charge end temp +20C to +30C"}


def temp(t):
    t = t.replace("C", "").replace("-", "−")
    return t


def dur(hms, up=False):
    """'1:27:24' / '29:08' -> '1:27 h' / '29 min' (bucket limits of the charge-time histograms)."""
    parts = [int(x) for x in hms.split(":")]
    sec = parts[-1] + 60 * parts[-2] + (3600 * parts[-3] if len(parts) == 3 else 0)
    if up:
        sec += 1                                     # upper limit 14:33 -> 14:34 ~ 15 min
    m = round(sec / 60)
    return f"{m} min" if m < 60 else f"{m // 60}:{m % 60:02d} h"


def label(addr, text):
    text = TYPO.get(addr, text) if addr != 0x907C else text
    t = " ".join(text.split())
    if t in FIXED:
        return FIXED[t]
    m = re.search(r"@ ([0-9]+)-([0-9]+)A", t) or re.search(r"@ ([0-9]+)A\+", t)
    if m:
        if addr == 0x907C:
            return "70–75 A"
        return f"{m.group(1)}–{m.group(2)} A" if m.lastindex == 2 else f"über {m.group(1)} A"
    m = re.match(r"Charge (started|ended) (.+)$", t)
    if m and "temp" not in t:
        when = "Beginn" if m.group(1) == "started" else "Ende"
        v = m.group(2).strip()
        if v.endswith("V+"):
            return f"{when} bei über {v[:-2]} V"
        return f"{when} bei {v[:-1].replace('-', '–').strip()} V"
    m = re.match(r"Charge (start|end) temp (.+?) to (.+)$", t)
    if m:
        when = "Beginn" if m.group(1) == "start" else "Ende"
        return f"{when} {temp(m.group(2))} … {temp(m.group(3))} °C"
    m = re.match(r"Charge (start|end) temp (.+?) and over$", t)
    if m:
        when = "Beginn" if m.group(1) == "start" else "Ende"
        return f"{when} ab {temp(m.group(2))} °C"
    m = re.match(r"(Dumb|Redlink) charge time \((.+)-(.+)\)$", t)
    if m:
        return f"{dur(m.group(2))} – {dur(m.group(3), up=True)}"
    raise SystemExit(f"no German label for 0x{addr:04X}: {t!r} - add it to FIXED in gen_regs.py")


TYPES = {"uint": "u", "date": "d", "hhmmss": "t", "ascii": "a", "sn": "s", "adc_t": "T", "dec_t": "F", "cell_v": "c"}


def table():
    rows = []
    for addr, length, dtype, text in m18.data_id:
        text = TYPO[addr] if addr == 0x90E8 else text
        rows.append([addr, length, TYPES[dtype], label(addr, text), group(addr)])
    # read by data_matrix, not described in data_id
    rows.append([0xA000, 6, "x", "Unbekannt (Block 0xA000, Rohdaten)", 9])
    return rows


def js():
    g = json.dumps([[n, h, u] for n, h, u in GROUPS], ensure_ascii=False, separators=(",", ":"))
    r = json.dumps(table(), ensure_ascii=False, separators=(",", ":"))
    return f"{BEGIN}\nconst REG_GROUPS={g};\nconst REGS={r};\n{END}"


def main():
    src = WEB_UI.read_text(encoding="utf-8")
    a, b = src.index(BEGIN), src.index(END) + len(END)
    new = src[:a] + js() + src[b:]
    if "--check" in sys.argv:
        if new != src:
            print("web_ui.h: register table outdated - run python esp32-bridge/tools/gen_regs.py")
            return 1
        print("web_ui.h: register table up to date")
        return 0
    WEB_UI.write_text(new, encoding="utf-8")
    print(f"web_ui.h: {len(table())} registers written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
