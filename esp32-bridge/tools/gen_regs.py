#!/usr/bin/env python3
"""
Generates the register table of the bridge's web page from m18.py's data_id,
so the phone shows every value the battery delivers - the same registers the
PC software reads - with German labels, grouped, histograms as bars.

    python esp32-bridge/tools/gen_regs.py          # rewrite web_ui.h
    python esp32-bridge/tools/gen_regs.py --check  # exit 1 if web_ui.h is outdated (CI)
"""
import json
import pathlib
